fun tinhDienTich(chieuDai: Double, chieuRong: Double): Double {
    return chieuDai * chieuRong
}

val ketQua1 = tinhDienTich(5.5, 3.0)
println("Dien tich hinh chu nhat 1 (5.5 x 3.0) là: $ketQua1")

val ketQua2 = tinhDienTich(12.0, 4.2)
println("Dien tich hinh chu nhat 2 (12.0 x 4.2) là: $ketQua2")